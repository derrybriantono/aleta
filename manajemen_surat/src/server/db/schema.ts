export async function ensureAletaSchema(db: AletaDatabase) {
  if (ensuredAletaSchemaDatabases.has(db)) {
    return;
  }

  for (const statement of schemaStatements) {
    await db.exec(statement);
  }

  for (const statement of aletaSippSchemaStatements) {
    await db.exec(statement);
  }

  for (const statement of migrationStatements) {
    await db.exec(statement);
  }

  for (const statement of jlfSeedStatements) {
    await db.exec(statement);
  }

  for (const statement of indexStatements) {
    if (!db.supportsFullTextSearch() && statement.includes("idx_letters_search_document_fts")) {
      continue;
    }
    await db.exec(statement);
  }

  await seedJlfVariableCatalog(db);
  ensuredAletaSchemaDatabases.add(db);
}
